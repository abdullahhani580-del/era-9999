// Persistent tracker for unrepeated quotes
const STORAGE_SEEN_QUOTES_KEY = 'era9999_seen_distinct_egyptian_quotes';

export function getSmartEgyptianQuote(category: 'break_entry' | 'break_exit' | 'all_finished' | 'study_continue'): EgyptianQuote {
  let pool = ALL_EGYPTIAN_QUOTES.filter((q) => q.category === category);
  if (pool.length === 0) pool = ALL_EGYPTIAN_QUOTES;

  let seenIds: string[] = [];
  try {
    const stored = localStorage.getItem(STORAGE_SEEN_QUOTES_KEY);
    if (stored) seenIds = JSON.parse(stored);
  } catch {
    seenIds = [];
  }

  // Filter pool for quotes not seen yet
  let available = pool.filter((q) => !seenIds.includes(q.id));

  // If all quotes in this category have been exhausted, reset seen IDs for this category
  if (available.length === 0) {
    seenIds = seenIds.filter((id) => !pool.some((q) => q.id === id));
    available = pool;
  }

  const chosen = available[Math.floor(Math.random() * available.length)] || pool[0];

  // Mark this specific quote as seen
  try {
    const updated = [...seenIds, chosen.id];
    localStorage.setItem(STORAGE_SEEN_QUOTES_KEY, JSON.stringify(updated));
  } catch {
    // Ignore storage errors
  }

  return chosen;
}
